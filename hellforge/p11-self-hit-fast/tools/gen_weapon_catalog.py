"""Generate src/weapon_catalog.h from HellForge's hellforge_content.h: armory weapons (type 1 primary, 2 support,
3 sidearm) with their entity resource ids, matched by display name.
  python -I gen_weapon_catalog.py <sdk folder> <out header>"""
import re, sys
text = open(sys.argv[1] + "/hellforge_content.h", encoding="utf-8").read()
items = re.findall(r"#define HF_ITEM_\w+ 0x[0-9A-Fa-f]+u\s*/\* (.+?) - armory type (\d) \*/", text)
ents = {}
for h, name in re.findall(r"#define HF_ENTITY_\w+ (0x[0-9A-Fa-f]+)(?:ull|ULL|u)?\s*/\* (.+?) \*/", text):
    ents.setdefault(name.strip(), h)
rows, missing = [], []
for name, kind in items:
    name = name.strip()
    if kind not in "123":
        continue
    h = ents.get(name)
    if not h:
        missing.append(name); continue
    shotgun = name.startswith("SG-") or "shotgun" in name.lower()
    rows.append((h, int(kind), shotgun, name))
with open(sys.argv[2], "w", encoding="utf-8", newline="\n") as f:
    f.write("/* Generated by tools/gen_weapon_catalog.py from HellForge's hellforge_content.h. */\n#pragma once\n")
    f.write("typedef struct WeaponEntry { uint64_t entity; uint8_t slot; uint8_t shotgun; const char* name; } WeaponEntry;\n")
    f.write("static const WeaponEntry kWeapons[] = {\n")
    for h, k, s, n in rows:
        f.write(f'    {{{h}ull, {k}, {int(s)}, "{n}"}},\n')
    f.write("};\n")
print(len(rows), "weapons; no entity for:", missing)
